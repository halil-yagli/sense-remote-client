// Sense Remote: writes bind_defaults.g.dart, the quiet default answer of every plain
// `flutter_ffi.rs` function (same return type the bridge generates), for the fake bridge in
// remote_chain_test.dart. Run from the repository root: node flutter/test/sense/session_integration/gen_bind_defaults.js
const fs = require('fs');
const src = fs.readFileSync('src/flutter_ffi.rs', 'utf8');
const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const base = (t) => {
  t = t.trim();
  const m = {
    String: ['String', "''"], bool: ['bool', 'false'], i32: ['int', '0'], i64: ['int', '0'],
    u32: ['int', '0'], usize: ['int', '0'], f64: ['double', '0.0'], '()': ['void', 'null'],
    'Vec<String>': ['List<String>', '<String>[]'], 'Option<String>': ['String?', 'null'],
    'Option<bool>': ['bool?', 'null'], 'Option<i32>': ['int?', 'null'],
    'Option<Vec<i32>>': ['List<int>?', 'null'],
  };
  return m[t] || null;
};
const out = [];
const re = /pub fn (\w+)\s*\(([\s\S]*?)\)\s*(?:->\s*([^{]+?))?\s*\{/g;
let x;
const seen = new Set();
while ((x = re.exec(src))) {
  const [, name, params, ret0] = x;
  if (params.includes('StreamSink') || seen.has(name)) continue;
  let ret = (ret0 || '()').trim();
  let sync = false;
  let m = ret.match(/^SyncReturn<(.+)>$/);
  if (m) { sync = true; ret = m[1]; }
  m = ret.match(/^(?:hbb_common::anyhow::Result|ResultType)<(.+)>$/);
  if (m) ret = m[1];
  const b = base(ret);
  if (!b) continue;
  seen.add(name);
  const [dt, dv] = b;
  const val = sync ? dv : (dt === 'void' ? 'Future<void>.value()' : `Future<${dt}>.value(${dv})`);
  out.push(`  '${camel(name)}': () => ${val},`);
}
fs.writeFileSync('flutter/test/sense/session_integration/bind_defaults.g.dart',
  `// GENERATED by gen_bind_defaults.js from src/flutter_ffi.rs. Do not edit.\n// ignore_for_file: prefer_void_to_null\nfinal Map<String, Object? Function()> kBindDefaults = {\n${out.join('\n')}\n};\n`);
console.log(out.length, 'defaults');
